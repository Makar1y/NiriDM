//! KDL handling.
//!
//! Two distinct formats live here:
//!
//! * [`generate_monitors_kdl`] produces the *niri* config fragment that NiriDM
//!   owns (`~/.config/NiriDM/monitors.kdl`, included from the main config with
//!   `include optional=true`). It is a strict subset of niri's
//!   `output { }` syntax and is the only file NiriDM ever rewrites.
//! * Layouts are persisted in `~/.config/NiriDM/layouts.kdl`. We parse that
//!   with a small hand-rolled lexer/parser for the exact KDL subset NiriDM
//!   emits, so a hand-edited file is understood without pulling in a full KDL
//!   implementation, and we emit it with an equally small printer.

use std::fmt::Write as _;

use crate::error::{NdError, Result};
use crate::layout::{Layout, ManagedOutput, MonitorMatch, Role};
use crate::types::{Output, Transform};

// ---------------------------------------------------------------------------
// monitors.kdl (niri fragment)
// ---------------------------------------------------------------------------

/// Render the niri `output { ... }` fragment for a matched layout applied to
/// the current connected set.
///
/// Only *connected* connectors get a block: a layout that manages a
/// not-yet-plugged monitor says nothing about it here (niri would otherwise
/// remember settings for a connector nobody can see). Connected connectors the
/// layout does not cover are explicitly turned off, so an "unmanaged" screen
/// never surprises the user (this is also the mechanism behind
/// `workspace-only display`: mark each output `off`).
///
/// String literals are rendered with `{:?}`, whose Rust escaping (`\"`, `\\`,
/// `\n`, ...) matches KDL's.
pub fn generate_monitors_kdl(connected: &[Output], layout: &Layout) -> String {
    let mut out = String::new();
    out.push_str("// Generated by NiriDM (Niri Display Manager). Do not edit.\n");

    for c in connected {
        match layout.outputs.iter().find(|o| o.connector == c.name) {
            Some(output) => write_output_block(&mut out, output),
            None => {
                let _ = writeln!(out, "output {:?} {{", c.name);
                out.push_str("    off\n");
                out.push_str("}\n");
            }
        }
    }

    for (workspace, connector) in &layout.workspaces {
        let _ = writeln!(out, "workspace {workspace:?} {{");
        let _ = writeln!(out, "    output {connector:?}");
        out.push_str("}\n");
    }

    out
}

fn write_output_block(out: &mut String, output: &ManagedOutput) {
    if matches!(output.role, Role::Off) {
        let _ = writeln!(out, "output {:?} {{", output.connector);
        out.push_str("    off\n");
        out.push_str("}\n");
        return;
    }

    let _ = writeln!(out, "output {:?} {{", output.connector);

    if let Some(mode) = &output.mode {
        let _ = writeln!(out, "    mode {mode:?}");
    }
    if let Some(scale) = output.scale {
        let _ = writeln!(out, "    scale {scale}");
    }
    if let Some(transform) = output.transform {
        let _ = writeln!(out, "    transform {:?}", transform.as_kdl_str());
    }
    if let Some((x, y)) = output.position {
        let _ = writeln!(out, "    position x={x} y={y}");
    }
    if output.vrr {
        out.push_str("    variable-refresh-rate\n");
    }

    out.push_str("}\n");
}

fn parse_transform(s: &str) -> Result<Transform> {
    Ok(match s {
        "normal" => Transform::Normal,
        "90" => Transform::Deg90,
        "180" => Transform::Deg180,
        "270" => Transform::Deg270,
        "flipped" => Transform::Flipped,
        "flipped-90" => Transform::Flipped90,
        "flipped-180" => Transform::Flipped180,
        "flipped-270" => Transform::Flipped270,
        other => return Err(NdError::Other(format!("invalid transform `{other}`"))),
    })
}

// ---------------------------------------------------------------------------
// layouts.kdl (NiriDM state)
// ---------------------------------------------------------------------------

const LAYOUTS_HEADER: &str = "\
// NiriDM layouts file. A `layout` node becomes active when its monitors
// match. `set` nodes form an exact set: every node must match a distinct
// connected monitor and no monitor may be left over. `match` nodes are
// OR-ed (kanshi style). Layouts are tried in file order.
";

/// Serialise layouts to the layout file.
pub fn emit_layouts(layouts: &[Layout]) -> String {
    let mut out = String::from(LAYOUTS_HEADER);
    for layout in layouts {
        emit_layout(&mut out, layout);
        out.push('\n');
    }
    out
}

fn emit_layout(out: &mut String, layout: &Layout) {
    let _ = writeln!(out, "layout {:?} {{", layout.name);

    for clause in &layout.set {
        out.push_str("    ");
        emit_monitor_match(out, "set", clause);
    }
    for clause in &layout.any {
        out.push_str("    ");
        emit_monitor_match(out, "match", clause);
    }

    if !layout.outputs.is_empty() {
        out.push('\n');
    }

    for output in &layout.outputs {
        let _ = writeln!(out, "    output {:?} {{", output.connector);
        match &output.role {
            Role::Off => out.push_str("        off\n"),
            Role::MirrorOf(target) => {
                let _ = writeln!(out, "        role mirror-of={target:?}");
            }
            Role::Normal => {}
        }
        if let Some(mode) = &output.mode {
            let _ = writeln!(out, "        mode {mode:?}");
        }
        if let Some(scale) = output.scale {
            let _ = writeln!(out, "        scale {scale}");
        }
        if let Some(transform) = output.transform {
            let _ = writeln!(out, "        transform {:?}", transform.as_kdl_str());
        }
        if let Some((x, y)) = output.position {
            let _ = writeln!(out, "        position x={x} y={y}");
        }
        if output.vrr {
            out.push_str("        variable-refresh-rate\n");
        }
        out.push_str("    }\n");
    }

    if !layout.outputs.is_empty() && !layout.workspaces.is_empty() {
        out.push('\n');
    }

    for (workspace, connector) in &layout.workspaces {
        let _ = writeln!(out, "    workspace {workspace:?} output={connector:?}");
    }

    out.push_str("}\n");
}

fn emit_monitor_match(out: &mut String, node: &str, clause: &MonitorMatch) {
    out.push_str(node);
    if let Some(v) = &clause.name {
        let _ = write!(out, " name={v:?}");
    }
    if let Some(v) = &clause.make {
        let _ = write!(out, " make={v:?}");
    }
    if let Some(v) = &clause.model {
        let _ = write!(out, " model={v:?}");
    }
    if let Some(v) = &clause.serial {
        let _ = write!(out, " serial={v:?}");
    }
    out.push('\n');
}

/// Parse a `layouts.kdl` document.
pub fn parse_layouts(input: &str) -> Result<Vec<Layout>> {
    let nodes = kdl_nodes(input)?;
    nodes.into_iter().map(interpret_layout).collect()
}

// ---------------------------------------------------------------------------
// KDL subset parser
// ---------------------------------------------------------------------------

#[derive(Debug, Clone, PartialEq)]
pub(crate) enum Val {
    Str(String),
    Num(f64),
}

#[derive(Debug, Clone, PartialEq)]
enum Tok {
    Ident(String),
    Str(String),
    Num(f64),
    Eq,
    LBrace,
    RBrace,
}

#[derive(Debug)]
pub(crate) struct Node {
    pub(crate) name: String,
    pub(crate) args: Vec<Val>,
    pub(crate) props: Vec<(String, Val)>,
    pub(crate) children: Vec<Node>,
}

fn interpret_layout(node: Node) -> Result<Layout> {
    if node.name != "layout" {
        return Err(NdError::Other(format!(
            "expected `layout` node, found `{}`",
            node.name
        )));
    }
    let name = match node.args.as_slice() {
        [Val::Str(s)] => s.clone(),
        _ => return Err(NdError::Other("`layout` needs a string name".into())),
    };

    let mut set = Vec::new();
    let mut any = Vec::new();
    let mut outputs = Vec::new();
    let mut workspaces = Vec::new();

    for child in node.children {
        match child.name.as_str() {
            "set" => set.push(interpret_monitor_match(&child, "set")?),
            "match" => any.push(interpret_monitor_match(&child, "match")?),
            "output" => outputs.push(interpret_output(&child)?),
            "workspace" => {
                let ws = match child.args.as_slice() {
                    [Val::Str(s)] => s.clone(),
                    _ => return Err(NdError::Other("`workspace` needs a string name".into())),
                };
                let output = match child.props.iter().find(|(k, _)| k == "output") {
                    Some((_, Val::Str(s))) => s.clone(),
                    _ => {
                        return Err(NdError::Other(
                            "`workspace` needs an output=\"...\" property".into(),
                        ))
                    }
                };
                workspaces.push((ws, output));
            }
            other => {
                return Err(NdError::Other(format!(
                    "unknown entry `{other}` inside layout \"{name}\""
                )))
            }
        }
    }

    Ok(Layout {
        name,
        set,
        any,
        outputs,
        workspaces,
    })
}

fn interpret_monitor_match(node: &Node, what: &str) -> Result<MonitorMatch> {
    if !node.args.is_empty() {
        return Err(NdError::Other(format!(
            "`{what}` takes no positional arguments"
        )));
    }
    let mut m = MonitorMatch::default();
    for (k, v) in &node.props {
        let Val::Str(s) = v else {
            return Err(NdError::Other(format!(
                "`{what}` property `{k}` must be a string"
            )));
        };
        match k.as_str() {
            "name" => m.name = Some(s.clone()),
            "make" => m.make = Some(s.clone()),
            "model" => m.model = Some(s.clone()),
            "serial" => m.serial = Some(s.clone()),
            _ => return Err(NdError::Other(format!("unknown `{what}` property `{k}`"))),
        }
    }
    if m.is_empty() {
        return Err(NdError::Other(format!(
            "`{what}` needs at least one property"
        )));
    }
    Ok(m)
}

fn interpret_output(node: &Node) -> Result<ManagedOutput> {
    let connector = match node.args.as_slice() {
        [Val::Str(s)] => s.clone(),
        _ => {
            return Err(NdError::Other(
                "`output` needs a string connector name".into(),
            ))
        }
    };

    let mut mode = None;
    let mut scale = None;
    let mut transform = None;
    let mut position = None;
    let mut vrr = false;
    let mut role = Role::Normal;

    for child in &node.children {
        match child.name.as_str() {
            "off" => role = Role::Off,
            "role" => {
                let target = match child.props.iter().find(|(k, _)| k == "mirror-of") {
                    Some((_, Val::Str(s))) => s.clone(),
                    _ => {
                        return Err(NdError::Other(
                            "`role` needs a mirror-of=\"...\" property".into(),
                        ))
                    }
                };
                role = Role::MirrorOf(target);
            }
            "mode" => {
                mode = Some(match child.args.as_slice() {
                    [Val::Str(s)] => s.clone(),
                    _ => return Err(NdError::Other("`mode` needs a string argument".into())),
                });
            }
            "scale" => {
                scale = Some(match child.args.as_slice() {
                    [Val::Num(n)] => *n,
                    _ => return Err(NdError::Other("`scale` needs a numeric argument".into())),
                });
            }
            "transform" => {
                transform = Some(match child.args.as_slice() {
                    [Val::Str(s)] => parse_transform(s)?,
                    _ => return Err(NdError::Other("`transform` needs a string argument".into())),
                });
            }
            "position" => {
                let x = match child.props.iter().find(|(k, _)| k == "x") {
                    Some((_, Val::Num(n))) => *n as i64,
                    _ => return Err(NdError::Other("`position` needs x=... and y=...".into())),
                };
                let y = match child.props.iter().find(|(k, _)| k == "y") {
                    Some((_, Val::Num(n))) => *n as i64,
                    _ => return Err(NdError::Other("`position` needs x=... and y=...".into())),
                };
                position = Some((x, y));
            }
            "variable-refresh-rate" => vrr = true,
            other => return Err(NdError::Other(format!("unknown `output` entry `{other}`"))),
        }
    }

    Ok(ManagedOutput {
        connector,
        mode,
        scale,
        transform,
        position,
        vrr,
        role,
    })
}

// -- lexer -- //

fn kdl_lex(input: &str) -> Result<Vec<Tok>> {
    let chars: Vec<char> = input.chars().collect();
    let mut toks = Vec::new();
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        if c.is_whitespace() {
            i += 1;
        } else if c == '/' && chars.get(i + 1) == Some(&'/') {
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
        } else if c == '{' {
            toks.push(Tok::LBrace);
            i += 1;
        } else if c == '}' {
            toks.push(Tok::RBrace);
            i += 1;
        } else if c == '=' {
            toks.push(Tok::Eq);
            i += 1;
        } else if c == '"' {
            let mut s = String::new();
            i += 1;
            let mut closed = false;
            while i < chars.len() {
                let ch = chars[i];
                if ch == '"' {
                    closed = true;
                    i += 1;
                    break;
                } else if ch == '\\' {
                    i += 1;
                    if i >= chars.len() {
                        return Err(NdError::Other("trailing `\\` in string".into()));
                    }
                    s.push(chars[i]);
                    i += 1;
                } else {
                    s.push(ch);
                    i += 1;
                }
            }
            if !closed {
                return Err(NdError::Other("unterminated string".into()));
            }
            toks.push(Tok::Str(s));
        } else if c.is_ascii_digit() || c == '-' {
            let start = i;
            if c == '-' {
                i += 1;
            }
            while i < chars.len() && (chars[i].is_ascii_digit() || chars[i] == '.') {
                i += 1;
            }
            let text: String = chars[start..i].iter().collect();
            let n: f64 = text
                .parse()
                .map_err(|_| NdError::Other(format!("invalid number `{text}`")))?;
            toks.push(Tok::Num(n));
        } else if c.is_alphabetic() || c == '_' {
            let start = i;
            while i < chars.len()
                && (chars[i].is_alphanumeric() || chars[i] == '_' || chars[i] == '-')
            {
                i += 1;
            }
            toks.push(Tok::Ident(chars[start..i].iter().collect()));
        } else {
            return Err(NdError::Other(format!(
                "unexpected character `{c}` in layouts file"
            )));
        }
    }
    Ok(toks)
}

// -- parser -- //

pub(crate) fn kdl_nodes(input: &str) -> Result<Vec<Node>> {
    let tokens = kdl_lex(input)?;
    Parser { tokens, pos: 0 }.nodes()
}

struct Parser {
    tokens: Vec<Tok>,
    pos: usize,
}

impl Parser {
    fn peek(&self) -> Option<&Tok> {
        self.tokens.get(self.pos)
    }

    fn nodes(&mut self) -> Result<Vec<Node>> {
        let mut out = Vec::new();
        while self.peek().is_some() {
            out.push(self.node()?);
        }
        Ok(out)
    }

    fn node(&mut self) -> Result<Node> {
        let Some(Tok::Ident(name)) = self.tokens.get(self.pos).cloned() else {
            return Err(NdError::Other("expected an identifier (node name)".into()));
        };
        self.pos += 1;

        let mut args = Vec::new();
        let mut props = Vec::new();

        loop {
            match self.peek() {
                Some(Tok::Str(_)) | Some(Tok::Num(_)) => {
                    let tok = self.tokens[self.pos].clone();
                    self.pos += 1;
                    match tok {
                        Tok::Str(s) => args.push(Val::Str(s)),
                        Tok::Num(n) => args.push(Val::Num(n)),
                        _ => unreachable!(),
                    }
                }
                Some(Tok::Ident(k)) => {
                    // `ident =` starts a property; bare `true`/`false` are KDL
                    // booleans and act as arguments; any other plain `ident`
                    // ends this (possibly childless) node and the sibling
                    // begins.
                    if matches!(self.tokens.get(self.pos + 1), Some(Tok::Eq)) {
                        let k = k.clone();
                        self.pos += 2;
                        let v = match self.tokens.get(self.pos).cloned() {
                            Some(Tok::Str(s)) => Val::Str(s),
                            Some(Tok::Num(n)) => Val::Num(n),
                            other => {
                                return Err(NdError::Other(format!(
                                    "expected a value after `{k}=`, found {other:?}"
                                )))
                            }
                        };
                        self.pos += 1;
                        props.push((k, v));
                    } else if matches!(k.as_str(), "true" | "false") {
                        args.push(Val::Str(k.to_owned()));
                        self.pos += 1;
                    } else {
                        return Ok(Node {
                            name,
                            args,
                            props,
                            children: Vec::new(),
                        });
                    }
                }
                Some(Tok::LBrace) => {
                    self.pos += 1;
                    let mut children = Vec::new();
                    loop {
                        match self.peek() {
                            Some(Tok::RBrace) => {
                                self.pos += 1;
                                break;
                            }
                            Some(_) => children.push(self.node()?),
                            None => return Err(NdError::Other("unclosed `{` block".into())),
                        }
                    }
                    return Ok(Node {
                        name,
                        args,
                        props,
                        children,
                    });
                }
                Some(Tok::Eq) => return Err(NdError::Other("stray `=` in layouts file".into())),
                Some(Tok::RBrace) | None => {
                    return Ok(Node {
                        name,
                        args,
                        props,
                        children: Vec::new(),
                    })
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = r#"
layout "Docked" {
    set serial="S4LMX3N00000"
    set model="U2723QE"

    output "DP-1" {
        mode "3840x2160@143.912"
        scale 1.0
        transform "90"
        position x=3840 y=0
        variable-refresh-rate
    }
    output "DP-2" {
        role mirror-of="DP-1"
    }
    output "eDP-1" {
        off
    }
    workspace "Chat" output="DP-1"
}
"#;

    #[test]
    fn parses_sample_layout() {
        let layouts = parse_layouts(SAMPLE).unwrap();
        assert_eq!(layouts.len(), 1);
        let l = &layouts[0];
        assert_eq!(l.name, "Docked");
        assert_eq!(l.set.len(), 2);
        assert_eq!(l.set[0].serial.as_deref(), Some("S4LMX3N00000"));
        assert_eq!(l.set[1].model.as_deref(), Some("U2723QE"));

        let dp1 = &l.outputs[0];
        assert_eq!(dp1.connector, "DP-1");
        assert_eq!(dp1.mode.as_deref(), Some("3840x2160@143.912"));
        assert_eq!(dp1.scale, Some(1.0));
        assert_eq!(dp1.transform, Some(Transform::Deg90));
        assert_eq!(dp1.position, Some((3840, 0)));
        assert!(dp1.vrr);

        assert!(matches!(&l.outputs[1].role, Role::MirrorOf(t) if t == "DP-1"));
        assert!(matches!(l.outputs[2].role, Role::Off));
        assert_eq!(l.workspaces, vec![("Chat".to_string(), "DP-1".to_string())]);
    }

    #[test]
    fn round_trips_emit_and_parse() {
        let layouts = parse_layouts(SAMPLE).unwrap();
        let emitted = emit_layouts(&layouts);
        let reparsed = parse_layouts(&emitted).unwrap();
        assert_eq!(layouts, reparsed);
    }

    #[test]
    fn escaping_survives_quotes_and_backslashes() {
        let mut layouts = parse_layouts(SAMPLE).unwrap();
        layouts[0].outputs[0].connector = "we\"ird\\name".into();
        let emitted = emit_layouts(&layouts);
        let reparsed = parse_layouts(&emitted).unwrap();
        assert_eq!(layouts, reparsed);
    }

    #[test]
    fn generates_off_for_unmanaged_connector() {
        let connected = vec![
            Output {
                name: "DP-1".into(),
                ..Default::default()
            },
            Output {
                name: "eDP-1".into(),
                ..Default::default()
            },
        ];
        let layouts = parse_layouts(SAMPLE).unwrap();
        let kdl = generate_monitors_kdl(&connected, &layouts[0]);

        // Layout covers DP-1, DP-2, eDP-1; only DP-1 and eDP-1 are present.
        assert!(kdl.contains("output \"DP-1\""));
        assert!(kdl.contains("output \"eDP-1\""));
        assert!(!kdl.contains("output \"DP-2\""));
        assert!(kdl.contains("mode \"3840x2160@143.912\""));
        assert!(kdl.contains("position x=3840 y=0"));
        assert!(kdl.contains("transform \"90\""));
        assert!(kdl.contains("variable-refresh-rate"));
        // eDP-1 is Role::Off => rendered as `off`.
        assert!(kdl.contains("off"));
    }

    #[test]
    fn generates_niri_workspace_blocks_for_routes() {
        let connected = vec![Output {
            name: "DP-1".into(),
            ..Default::default()
        }];
        let layouts = parse_layouts(SAMPLE).unwrap();
        let kdl = generate_monitors_kdl(&connected, &layouts[0]);

        // routes live in layouts.kdl as `output="..."` props; in monitors.kdl
        // they become niri's `workspace "name" { output "X" }` shape.
        assert!(
            kdl.contains("workspace \"Chat\" {\n    output \"DP-1\"\n}\n"),
            "workspace block missing:\n{kdl}"
        );
    }
}
