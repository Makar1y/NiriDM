//! KDL handling.
//!
//! Two distinct formats live here:
//!
//! * [`generate_monitors_kdl`] produces the *niri* config fragment that NiriDM
//!   owns (`~/.config/NiriDM/monitors.kdl`, included from the main config with
//!   `include optional=true`). It is a strict subset of niri's
//!   `output { }` syntax and is the only file NiriDM ever rewrites.
//! * Layouts NiriDM persists in `~/.config/NiriDM/layouts.kdl` (see
//!   [`Layout`](crate::layout::Layout)). We parse that with a small hand-rolled
//!   lexer/parser for the exact KDL subset NiriDM emits, so a hand-edited file is
//!   understood without pulling in a full KDL implementation, and we emit it
//!   with an equally small printer.

use std::fmt::Write as _;
use std::marker::PhantomData;

use crate::error::{NdError, Result};
use crate::layout::{ManagedOutput, MonitorMatch, Role, Transform};
use crate::types::Output;

// ---------------------------------------------------------------------------
// monitors.kdl (niri fragment)
// ---------------------------------------------------------------------------

/// Render the niri `output { ... }` fragment for a matched layout applied to
/// the current connected set.
///
/// Every connected connector not covered by the layout is explicitly turned
/// off, so an "unmanaged" screen never surprises the user (this is also the
/// mechanism behind `workspace-only display`: mark each output `off`).
pub fn generate_monitors_kdl(connected: &[Output], layout: &Layout) -> String {
    let mut out = String::new();
    out.push_str("// Generated by NiriDM (Niri Display Manager). Do not edit.\n");

    let managed: std::collections::HashSet<&str> =
        layout.outputs.iter().map(|o| o.connector.as_str()).collect();

    for output in &layout.outputs {
        write_output_block(&mut out, output);
    }

    for c in connected {
        if !managed.contains(c.name.as_str()) {
            let _ = writeln!(out, "output {:?} {{", kdl_escape(&c.name));
            out.push_str("    off\n");
            out.push_str("}\n");
        }
    }

    out
}

fn write_output_block(out: &mut String, output: &ManagedOutput) {
    if matches!(output.role, Role::Off) {
        let _ = writeln!(out, "output {:?} {{", kdl_escape(&output.connector));
        out.push_str("    off\n");
        out.push_str("}\n");
        return;
    }

    let _ = writeln!(out, "output {:?} {{", kdl_escape(&output.connector));

    if let Some(mode) = &output.mode {
        let _ = writeln!(out, "    mode {:?}", kdl_escape(mode));
    }
    if let Some(scale) = output.scale {
        let _ = writeln!(out, "    scale {scale}");
    }
    if let Some(transform) = output.transform {
        let _ = writeln!(out, "    transform {:?}", kdl_escape(transform.as_kdl_str()));
    }
    if let Some((x, y)) = output.position {
        let _ = writeln!(out, "    position x={x} y={y}");
    }
    if output.vrr {
        out.push_str("    variable-refresh-rate\n");
    }

    out.push_str("}\n");
}

/// KDL string literal escaping (`\` and `"`).
fn kdl_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            _ => out.push(ch),
        }
    }
    out
}

fn parse_transform(s: &str) -> Result<Transform> {
    Ok(match s {
        "normal" => Transform::Normal,
        "90" => Transform::Deg90,
        "180" => Transform::Deg180,
        "270" => Transform::Deg270,
        "flipped" => Transform::Flipped,
        "flipped-90" => Transform::Flipped90,
        "flipped-180" => Transform::Flipped180,
        "flipped-270" => Transform::Flipped270,
        other => return Err(NdError::Other(format!("invalid transform `{other}`"))),
    })
}

// ---------------------------------------------------------------------------
// layouts.kdl (NiriDM state)
// ---------------------------------------------------------------------------

const LAYOUTS_HEADER: &str =
    "// NiriDM layouts file. A `layout` node becomes active when its monitors\n\
     // match. `set` nodes form an exact set: every node must match a distinct\n\
     // connected monitor and no monitor may be left over. `match` nodes are\n\
     // OR-ed (kanshi style). Layouts are tried in file order.\n";

const SAMPLE_LAYOUTS: &str = r#"layout "Docked" {
    // Exact set: this layout applies only when these monitors are all there
    // and nothing else is connected besides the laptop screen.
    set serial="S4LMX3N00000"
    set model="U2723QE"

    output "DP-1" {
        mode "3840x2160@143.912"
        scale 1.0
        transform "90"
        position x=3840 y=0
    }
    output "DP-2" {
        role mirror-of="DP-1"
    }
    output "eDP-1" {
        off
    }
    workspace "Chat" output="DP-1"
}
"#;

/// Serialise layouts to the layout file.
pub fn emit_layouts(layouts: &[Layout]) -> String {
    let mut out = String::from(LAYOUTS_HEADER);
    for layout in layouts {
        emit_layout(&mut out, layout);
        out.push('\n');
    }
    out
}

fn emit_layout(out: &mut String, layout: &Layout) {
    let _ = writeln!(out, "layout {:?} {{", kdl_escape(&layout.name));

    for clause in &layout.set {
        out.push_str("    ");
        emit_monitor_match(out, "set", clause);
    }
    for clause in &layout.any {
        out.push_str("    ");
        emit_monitor_match(out, "match", clause);
    }

    if !layout.outputs.is_empty() {
        out.push('\n');
    }

    for output in &layout.outputs {
        let _ = writeln!(out, "    output {:?} {{", kdl_escape(&output.connector));
        match &output.role {
            Role::Off => out.push_str("        off\n"),
            Role::MirrorOf(target) => {
                let _ = writeln!(
                    out,
                    "        role mirror-of={:?}",
                    kdl_escape(target)
                );
            }
            Role::Normal => {}
        }
        if let Some(mode) = &output.mode {
            let _ = writeln!(out, "        mode {:?}", kdl_escape(mode));
        }
        if let Some(scale) = output.scale {
            let _ = writeln!(out, "        scale {scale}");
        }
        if let Some(transform) = output.transform {
            let _ = writeln!(out, "        transform {:?}", kdl_escape(transform.as_kdl_str()));
        }
        if let Some((x, y)) = output.position {
            let _ = writeln!(out, "        position x={x} y={y}");
        }
        if output.vrr {
            out.push_str("        variable-refresh-rate\n");
        }
        out.push_str("    }\n");
    }

    if !layout.outputs.is_empty() && !layout.workspaces.is_empty() {
        out.push('\n');
    }

    for (workspace, connector) in &layout.workspaces {
        let _ = writeln!(
            out,
            "    workspace {:?} output={:?}",
            kdl_escape(workspace),
            kdl_escape(connector)
        );
    }

    out.push_str("}\n");
}

fn emit_monitor_match(out: &mut String, node: &str, clause: &MonitorMatch) {
    out.push_str(node);
    if let Some(v) = &clause.name {
        let _ = write!(out, " name={:?}", kdl_escape(v));
    }
    if let Some(v) = &clause.make {
        let _ = write!(out, " make={:?}", kdl_escape(v));
    }
    if let Some(v) = &clause.model {
        let _ = write!(out, " model={:?}", kdl_escape(v));
    }
    if let Some(v) = &clause.serial {
        let _ = write!(out, " serial={:?}", kdl_escape(v));
    }
    out.push('\n');
}

